FIRST, LAST = 0x20, 0x7E
ROWS = 9


def pack() -> tuple[list[int], list[int]]:
    """Pack the glyphs into a bitmap and a width table."""
    data: list[int] = []
    widths: list[int] = []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        rows = G.get(ch)
        if rows is None:
            raise SystemExit(f"no glyph drawn for {ch!r} (U+{code:04X})")
        width = max(len(r) for r in rows)
        if width > 8:
            raise SystemExit(f"glyph {ch!r} is {width} columns, but the cell holds 8")
        if len(rows) > ROWS:
            raise SystemExit(f"glyph {ch!r} has {len(rows)} rows, but the cell holds {ROWS}")
        for y in range(ROWS):
            row = rows[y] if y < len(rows) else ""
            bits = 0
            for x, c in enumerate(row):
                if c == "#":
                    bits |= 1 << (7 - x)
                elif c != ".":
                    raise SystemExit(f"glyph {ch!r} row {y} has {c!r}, expected '#' or '.'")
            data.append(bits)
        # " " carries no ink, so give it a sensible advance of its own.
        widths.append(3 if ch == " " else width)
    return data, widths


def main() -> None:
    """Generate `src/render/font_data.rs` from the glyph drawings above."""
    data, widths = pack()
    out = pathlib.Path("src/render/font_data.rs")
    lines = [
        "//! Bitmap glyphs for [`super::font`]. Generated by `tools/gen_font.py`.",
        "//! Edit the drawings there, not the bytes here.",
        "",
        "/// Code point of the first glyph in the table.",
        f"pub const FIRST: u8 = {FIRST};",
        "/// Code point of the last glyph in the table.",
        f"pub const LAST: u8 = {LAST};",
        "/// Rows per glyph cell. Rows 0-6 are the cap height, while 7-8 are descenders.",
        f"pub const ROWS: usize = {ROWS};",
        "/// Rows above the baseline, which sits directly under row 6.",
        "pub const BASELINE: usize = 7;",
        "",
        "/// Ink columns of each glyph, leftmost column in bit 7.",
        f"pub static BITMAP: [u8; {len(data)}] = [",
    ]
    for i in range(0, len(data), ROWS):
        row = ", ".join(f"0x{b:02x}" for b in data[i : i + ROWS])
        lines.append(f"    {row}, // {chr(FIRST + i // ROWS)!r}")
    lines.extend(("];", "", "/// Ink width of each glyph, in columns.", f"pub static WIDTHS: [u8; {len(widths)}] = ["))
    lines.extend("    " + ", ".join(str(w) for w in widths[i : i + 16]) + "," for i in range(0, len(widths), 16))
    lines.append("];")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out} ({len(data)} bytes of glyph data, {len(widths)} glyphs)")


if __name__ == "__main__":
    main()
